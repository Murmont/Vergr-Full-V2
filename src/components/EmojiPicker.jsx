const CATEGORY_ICONS = {
  'Smileys': 'sentiment_satisfied', 'People': 'person', 'Animals': 'pets',
  'Food': 'restaurant', 'Gaming': 'sports_esports', 'Travel': 'flight',
  'Objects': 'lightbulb', 'Symbols': 'tag', 'Flags': 'flag',
};

const RECENT_KEY = 'vergr_recent_emojis';
const MAX_RECENT = 32;

function getRecent() { try { return JSON.parse(localStorage.getItem(RECENT_KEY)) || []; } catch { return []; } }
function addRecent(emoji) {
  try {
    let r = getRecent().filter(x => x !== emoji);
    r.unshift(emoji);
    localStorage.setItem(RECENT_KEY, JSON.stringify(r.slice(0, MAX_RECENT)));
  } catch {}
}

export default function EmojiPicker({ onSelect, onClose }) {
  const [category, setCategory] = useState(() => getRecent().length > 0 ? '__recent__' : 'Smileys');
  const [search, setSearch] = useState('');
  const searchRef = useRef(null);
  const recent = useMemo(() => getRecent(), []);

  const handleSelect = useCallback((emoji) => { addRecent(emoji); onSelect(emoji); }, [onSelect]);

  const searchResults = useMemo(() => {
    if (!search.trim()) return null;
    const q = search.toLowerCase().trim();
    const matches = new Set();
    for (const [keyword, emojis] of Object.entries(SEARCH_INDEX)) {
      if (keyword.includes(q) || q.includes(keyword)) emojis.forEach(e => matches.add(e));
    }
    for (const [cat, emojis] of Object.entries(EMOJI_DATA)) {
      if (cat.toLowerCase().includes(q)) emojis.forEach(e => matches.add(e));
    }
    return [...matches];
  }, [search]);

  const displayEmojis = searchResults || (category === '__recent__' ? recent : (EMOJI_DATA[category] || []));

  return (
    <div className="bg-surface-1 border-t border-white/[0.04] flex flex-col" style={{ height: 260 }}>
      <div className="px-2 pt-2 pb-1">
        <div className="flex items-center bg-surface-2 border border-white/[0.06] rounded-lg px-2.5 gap-2 focus-within:border-brand-cyan/40 transition-colors">
          <Icon name="search" size={16} className="text-text-muted shrink-0" />
          <input ref={searchRef} type="text" placeholder="Search emoji..." value={search}
            onChange={e => { setSearch(e.target.value); if (e.target.value) setCategory(''); }}
            className="flex-1 bg-transparent py-1.5 text-xs text-white outline-none placeholder:text-text-muted/60" />
          {search && (
            <button onClick={() => { setSearch(''); setCategory('Smileys'); searchRef.current?.focus(); }} className="text-text-muted hover:text-white">
              <Icon name="close" size={14} />
            </button>
          )}
        </div>
      </div>

      {!search && (
        <div className="flex items-center border-b border-white/[0.04] px-0.5 shrink-0">
          <button onClick={() => setCategory('__recent__')}
            className={`flex-1 py-1.5 flex items-center justify-center transition-all relative ${
              category === '__recent__' ? 'text-brand-cyan' : 'text-text-muted hover:text-text-secondary'
            }`}>
            <Icon name="schedule" size={16} />
            {category === '__recent__' && <div className="absolute bottom-0 left-1/4 right-1/4 h-0.5 bg-brand-cyan rounded-full" />}
          </button>
          {Object.entries(CATEGORY_ICONS).map(([cat, icon]) => (
            <button key={cat} onClick={() => setCategory(cat)}
              className={`flex-1 py-1.5 flex items-center justify-center transition-all relative ${
                category === cat ? 'text-brand-cyan' : 'text-text-muted hover:text-text-secondary'
              }`}>
              <Icon name={icon} size={16} />
              {category === cat && <div className="absolute bottom-0 left-1/4 right-1/4 h-0.5 bg-brand-cyan rounded-full" />}
            </button>
          ))}
        </div>
      )}

      <p className="text-[9px] font-bold text-text-muted uppercase tracking-widest px-3 py-1">
        {search ? `Results for "${search}"` : category === '__recent__' ? 'Recently Used' : category}
      </p>

      <div className="flex-1 overflow-y-auto no-scrollbar px-1 pb-1">
        <div className="grid grid-cols-8 lg:grid-cols-10 xl:grid-cols-12">
          {displayEmojis.map((emoji, i) => (
            <button key={`${emoji}-${i}`} onClick={() => handleSelect(emoji)}
              className="flex items-center justify-center w-full aspect-square text-[22px] lg:text-[24px] rounded-md hover:bg-surface-2/60 active:scale-75 transition-transform"
              role="img">
              {emoji}
            </button>
          ))}
        </div>
        {displayEmojis.length === 0 && (
          <div className="py-6 text-center">
            <p className="text-text-muted text-xs">
              {search ? `No emojis found for "${search}"` : category === '__recent__' ? 'No recently used emojis' : 'No emojis'}
            </p>
          </div>
        )}
      </div>
    </div>
  );
}