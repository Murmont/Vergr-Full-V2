#!/usr/bin/env node
// Generate an RSA-OAEP 3072-bit keypair for KYC data-key wrapping.
// - Writes the PUBLIC key (SPKI / PEM) to src/constants/kycPublicKey.js
// - Prints the PRIVATE key (PKCS#8 / PEM) to stdout ONLY
//
// Take the printed private key and store it in Google Cloud Secret Manager:
//   gcloud secrets create kyc-private-key --replication-policy=automatic
//   gcloud secrets versions add kyc-private-key --data-file=- < /path/to/private.pem
// (Or paste via the GCP console UI.)
//
// Grant the Cloud Functions service account secretmanager.secretAccessor on
// the secret. The private key is ONLY read inside the reviewKyc / decideKyc
// callables.
//
// NEVER commit the private key. The public key is safe to embed client-side.
//
// Run: node scripts/generate-kyc-keypair.cjs

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const { publicKey, privateKey } = crypto.generateKeyPairSync('rsa', {
  modulusLength: 3072,
  publicKeyEncoding: { type: 'spki', format: 'pem' },
  privateKeyEncoding: { type: 'pkcs8', format: 'pem' },
});

const constPath = path.join(__dirname, '..', 'src', 'constants', 'kycPublicKey.js');
fs.mkdirSync(path.dirname(constPath), { recursive: true });
fs.writeFileSync(
  constPath,
  `// AUTO-GENERATED by scripts/generate-kyc-keypair.cjs
// Do not edit by hand. Re-run the script to rotate.
// This is the PUBLIC half of the KYC data-key wrapping keypair.
// Safe to commit and ship to the browser.
export const KYC_PUBLIC_KEY_PEM = \`${publicKey.trim()}\`;

// Matches the key size / hash used on the server side.
export const KYC_WRAP_ALG = { name: 'RSA-OAEP', hash: 'SHA-256' };
`
);

console.log('\n✅ Public key written to src/constants/kycPublicKey.js\n');
console.log('=== PRIVATE KEY — store in Secret Manager as `kyc-private-key` ===\n');
console.log(privateKey);
console.log('=== END PRIVATE KEY ===\n');
console.log('Next:');
console.log('  1. echo above private key into a file, e.g. kyc-priv.pem');
console.log('  2. gcloud secrets create kyc-private-key --replication-policy=automatic');
console.log('  3. gcloud secrets versions add kyc-private-key --data-file=kyc-priv.pem');
console.log('  4. shred -u kyc-priv.pem');
console.log('  5. NEVER commit the file.');
